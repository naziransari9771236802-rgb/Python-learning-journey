# 4. HOW DOES PYTHON WORK?
# ============================================================
#
# Python is an interpreted programming language.
#
# In simple terms:
#
# Step 1: We write Python code in a .py file.
#
# Step 2: The Python interpreter processes the code.
#
# Step 3: Python executes the instructions.
#
# Step 4: We get the output.
#
# Example:
#
# print(10 + 20)
#
# Output:
# 30
#
# When Python runs a program, its implementation generally
# converts source code into bytecode, which is executed by
# the Python Virtual Machine (PVM).
#
# Note:
# The exact execution process can vary between Python
# implementations.


