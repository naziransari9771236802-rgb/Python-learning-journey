# 1. WHAT IS PYTHON?
#
# Python is a high-level, interpreted, general-purpose
# programming language.
#
# It was created by Guido van Rossum and was first released
# in 1991.
#
# Python is known for its simple syntax, readability,
# flexibility, and large collection of libraries.
#
# It allows developers to write programs using fewer lines
# of code compared to many other programming languages.
#
# Example:
#
# print("Hello, World!")
#
