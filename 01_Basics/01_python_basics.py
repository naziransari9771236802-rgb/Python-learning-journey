# 10. PYTHON CHARACTER SET
# ============================================================
#
# A character set is a set of valid characters that can be
# used to write Python programs.
#
# Python supports Unicode, which allows us to use characters
# from different languages and symbols.
#
# The Python character set includes the following:
#
# 1. Letters:
#    - Uppercase letters: A to Z
#    - Lowercase letters: a to z
#
# 2. Digits:
#    - Numbers from 0 to 9
#
# 3. Special Symbols:
#    +, -, *, /, %, =, <, >, !, &, |, etc.
#
# 4. Whitespace Characters:
#    - Space
#    - Tab
#    - Newline
#
# 5. Unicode Characters:
#    Python supports Unicode characters, including characters
#    from different languages and special symbols.
#
# Example:
#
# name = "Nazir"
# age = 21

# print(name)
# print(age)
#
# Output:
# Nazir
# 21
